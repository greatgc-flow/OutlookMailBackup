#!/usr/bin/env python3
"""Build the single importable BAS, or check it without changing the checkout.

Requires Python 3.10+ and its standard library. The original assembler and source
fragments run in a temporary directory so generated files never pollute sources.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
DEVELOPMENT = ROOT / "development"
ARTIFACT = ROOT / "OutlookMailBackup.bas"


def stage_sources(destination: Path) -> None:
    """Copy only files explicitly named by the unmodified original assembler."""
    assembler = DEVELOPMENT / "mb_assemble.py"
    parsed = ast.parse(assembler.read_text(encoding="ascii"))
    assignments = [
        node for node in parsed.body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "PARTS"
                for target in node.targets)
    ]
    if len(assignments) != 1:
        raise ValueError("Assembler must contain exactly one PARTS assignment")
    parts = ast.literal_eval(assignments[0].value)
    if not isinstance(parts, list) or not parts:
        raise ValueError("Assembler PARTS must be a nonempty list")
    for name in parts:
        if (not isinstance(name, str) or Path(name).name != name
                or not name.endswith(".basfrag")):
            raise ValueError(f"Unexpected source fragment path: {name!r}")
        shutil.copyfile(DEVELOPMENT / name, destination / name)
    shutil.copyfile(assembler, destination / assembler.name)


def assemble(destination: Path) -> bytes:
    stage_sources(destination)
    completed = subprocess.run(
        [sys.executable, "mb_assemble.py"], cwd=destination,
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace",
    )
    if completed.returncode:
        raise RuntimeError("Assembler failed:\n" + completed.stdout)
    return (destination / ARTIFACT.name).read_bytes()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="compare the regenerated bytes; do not overwrite the BAS")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="outlookmailbackup-build-") as temporary:
        data = assemble(Path(temporary))
    digest = hashlib.sha256(data).hexdigest()
    if args.check:
        if not ARTIFACT.is_file() or ARTIFACT.read_bytes() != data:
            print("FAIL: OutlookMailBackup.bas differs from the assembled sources.",
                  file=sys.stderr)
            print("Run python tools/build.py to regenerate it.", file=sys.stderr)
            return 1
        print(f"PASS: byte-identical BAS ({len(data):,} bytes)")
    else:
        ARTIFACT.write_bytes(data)
        print(f"Built OutlookMailBackup.bas ({len(data):,} bytes)")
    print(f"SHA256: {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
